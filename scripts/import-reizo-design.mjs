/** Compile the supplied, trusted design into scoped assets. No demo auth or account scripts ship. */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const postcss = require('postcss');
const ts = require('typescript');
const source = path.resolve('design/reizo-20261008/site');
const out = path.resolve('src/components/reizo/generated');
fs.mkdirSync(out, { recursive: true });
const routes = { 'index.html':'/', 'agent.html':'/agent', 'studio.html':'/studio', 'api.html':'/models', 'business.html':'/business', 'pricing.html':'/pricing', 'account.html':'/account', 'docs.html':'/docs', 'cases.html':'/cases', 'support.html':'/support', 'business-contact.html':'/business/contact' };
const accountSections = { keys:'keys', billing:'wallet', membership:'pricing', settings:'personalization', developer:'tasks', referrals:'invite', logs:'logs', team:'team', settlement:'enterprise', security:'security', preferences:'personalization', overview:'' };
const rewrite = text => Object.entries(routes).reduce((v,[from,to])=>v.replaceAll(from,to), text.replaceAll('assets/', '/reizo/assets/').replace(/account\.html#([a-z-]+)/g,(match,section)=>section in accountSections ? `/account${accountSections[section] ? '/'+accountSections[section] : ''}` : match));
const apiHtml = fs.readFileSync(path.join(source,'api.html'),'utf8');
fs.writeFileSync(path.join(out,'api-hero.json'),JSON.stringify({__html:rewrite(apiHtml.match(/<section class="api-hero shell"[^>]*>([\s\S]*?)<\/section>/)[1])},null,2)+'\n');
const pricingHtml = fs.readFileSync(path.join(source,'pricing.html'),'utf8');
fs.writeFileSync(path.join(out,'pricing-comparison.json'), JSON.stringify({__html:rewrite(pricingHtml.match(/  <section class="usage-comparison[\s\S]*?(?=  <section class="pricing-faq)/)[0])},null,2)+'\n');
const pages = ['index','agent','business','cases','support','business-contact'];
const styles = new Set(['ui.css','platform-nav.css','account-nav.css','api.css','pricing.css','pricing-compare.css','account.css','site-pages.css']);
for (const page of pages) {
  const html = fs.readFileSync(path.join(source, `${page}.html`), 'utf8');
  for (const match of html.matchAll(/<link[^>]+href="([^"]+\.css)(?:\?[^"]*)?"[^>]*>/g)) {
    if (!/theme-|site-theme|palette-preview|account-welcome|account-avatar/.test(match[1])) styles.add(match[1]);
  }
  let body = html.match(/<body[^>]*>([\s\S]*?)<\/body>/)[1];
  body = body.replace(/<script\b[^>]*>[\s\S]*?<\/script>/g,'').replace(/<aside[^>]*class="[^"]*palette[^>]*>[\s\S]*?<\/aside>/g,'');
  // The shared React header owns navigation and real account state.
  body = body.replace(/<header class="site-header(?: [^"]*)?"[^>]*>[\s\S]*?<\/header>/,'');
  body = body.replace(/<dialog\b[^>]*id="site-login-dialog"[^>]*>[\s\S]*?<\/dialog>/g, '');
  body = rewrite(body);
  if (page === 'agent') {
    body = body.replace(/src="\/studio(?:\?[^"]*)?"/g, 'src="/reizo/showcase/index.html"')
      .replace('可交互的 REIZO 工作台设计预览，不调用模型', 'REIZO 工作台成果示例')
      .replace(/设计预览，不调用模型/g, '视频、图片与文档成果示例')
      .replace('可以选任务、切换模型、确认方向，或展开画布。示例内容不会调用模型或产生费用。', '体验新版任务流程，查看图片、分镜与文档示例。这里为交互演示，不调用模型，也不产生费用。');
  }
  const bodyClass = html.match(/<body[^>]*class="([^"]*)"/)?.[1] ?? '';
  fs.writeFileSync(path.join(out, `${page}.json`), JSON.stringify({html:body,bodyClass},null,2)+'\n');
}
// Preserve original stylesheet order. Prefix every selector to prevent collisions
// with existing console and editor components. Body tokens belong to the wrapper.
let css = '/* Generated by scripts/import-reizo-design.mjs. */\n';
for (const name of styles) {
  const owner = name.startsWith('business') || name==='enterprise-security.css' ? 'business' : name==='api.css' ? 'api' : name==='pricing.css' ? 'pricing' : name==='account.css' ? 'account' : name==='agent.css' ? 'agent' : null;
  const scope = owner ? `.reizo-site.reizo-page-${owner}` : '.reizo-site';
  const sheet = postcss.parse(fs.readFileSync(path.join(source,name),'utf8'));
  sheet.walkRules(rule=>{
    if (rule.parent.type==='atrule' && /keyframes$/.test(rule.parent.name)) return;
    rule.selectors = rule.selectors.map(selector=> {
      const themeAncestor = selector.match(/^(html\[data-theme[^\]]*\])\s+/)?.[0] ?? '';
      const s=selector.slice(themeAncestor.length).replace(/:root/g,scope).replace(/(^|[\s>+~,(])(?:html|body)(?=[\s.#:[>+~)]|$)/g,(_match,prefix)=>prefix+scope);
      if (/^\.(?:home-page|business-page|api-page|pricing-page|account-page|agent-page|subpage)(?=[\s.#:[>+~]|$)/.test(s)) return `${themeAncestor}${scope}${s}`;
      return themeAncestor + (s.startsWith(scope) ? s : `${scope} ${s}`);
    });
  });
  css += `\n/* ${name} */\n${rewrite(sheet.toString())}\n`;
}
fs.writeFileSync(path.join(out,'design.css'),css);
// This sheet has explicit html[data-theme] ancestors, so keep them global and
// put its palette on the React page surface instead of the prototype body.
const theme = postcss.parse(rewrite(fs.readFileSync(path.join(source,'site-theme.css'),'utf8')));
theme.walkRules(rule => {
  rule.selectors = rule.selectors.map(selector => selector.replace(/^(html\[data-theme(?:=dark)?\])(?:\s+(.*))?$/, (_, ancestor, rest) => {
    if (!rest) return ancestor;
    const surface = '.reizo-site[class*="reizo-page-"]';
    if (rest === 'body') return `${ancestor} ${surface}`;
    if (rest.startsWith('body:not(')) return `${ancestor} ${surface}${rest.slice(4)}`;
    if (rest.startsWith(':is(.agent-page,')) return `${ancestor} ${surface}${rest}`;
    return `${ancestor} ${surface} ${rest.replace(/^body\s+/, '')}`;
  }));
});
fs.writeFileSync(path.join(out,'theme.css'),theme.toString());
const scripts = ['home','showcase-scenes','capability-stage','pricing-compare','connected-work','woven-divider','business','business-motion','business-particles','site-pages'];
for (const name of scripts) {
  let code = rewrite(fs.readFileSync(path.join(source,`${name}.js`),'utf8'));
  // Navigation is React-owned. Keep the original presentation animations only.
  if(name==='ui') code=code.replace(/  \/\/ Navigation and unfinished product destinations\.[\s\S]*?  let toastTimer;/,'  let toastTimer;');
  if(name==='business') code=code.replace(/  function closeNav\(\)[\s\S]*?  const dialog=/,'  const closeNav = () => {};\n  const dialog=');
  if(name==='site-pages') code=code.replace(/  const menu = [\s\S]*?  document.querySelectorAll\('\[data-draft-form\]'\)/,"  document.querySelectorAll('[data-draft-form]')");
  if(name==='home') {
    code=code.replace(/  const menu=.*?[\s\S]*?  const scenes=/,'  const scenes=');
    code=code.replace("$('.site-header').classList.toggle('is-compact',scrollY>70);",'');
  }
  // Register every listener with the component lifetime, including dynamically
  // created demo controls. Timers and observers use the same disposable scope.
  const ast=ts.createSourceFile(`${name}.js`,code,ts.ScriptTarget.Latest,true,ts.ScriptKind.JS);
  const result=ts.transform(ast,[context=>{
    const visit=node=>{
      if(ts.isCallExpression(node)&&ts.isIdentifier(node.expression)&&node.expression.text==='addEventListener') {
        return ts.factory.createCallExpression(ts.factory.createPropertyAccessExpression(ts.factory.createIdentifier('lifetime'),'listen'),undefined,[ts.factory.createIdentifier('window'),...node.arguments.map(a=>ts.visitNode(a,visit))]);
      }
      if(ts.isCallExpression(node)&&ts.isPropertyAccessExpression(node.expression)&&node.expression.name.text==='addEventListener') {
        return ts.factory.createCallExpression(ts.factory.createPropertyAccessExpression(ts.factory.createIdentifier('lifetime'),'listen'),undefined,[ts.visitNode(node.expression.expression,visit),...node.arguments.map(a=>ts.visitNode(a,visit))]);
      }
      return ts.visitEachChild(node,visit,context);
    };
    return node=>ts.visitNode(node,visit);
  }]);
  code=ts.createPrinter().printFile(result.transformed[0]);result.dispose();
  fs.writeFileSync(path.join(out,`${name}.js`),`/* eslint-disable */\n// Generated from the supplied design; managed by createDesignScope.\nexport default function initialize(lifetime) {\nconst { document, window, setTimeout, clearTimeout, setInterval, clearInterval, requestAnimationFrame, cancelAnimationFrame, IntersectionObserver, ResizeObserver, MutationObserver } = lifetime;\n${code}\n}\n`);
}
console.log(`Imported ${pages.length} presentation pages and ${styles.size} scoped stylesheets.`);

// Isolated marketing preview. Never ship the review package's mock login/account.
const showcase = path.resolve('public/reizo/showcase');
fs.mkdirSync(showcase, {recursive:true});
const previewFiles = ['studio.css','studio-review.css','studio-library.css','demo-deliverables.css','demo-deliverables.js','studio.js','studio-review.js','account-nav.css','site-theme.css','site-theme.js'];
for (const name of previewFiles) {
  let contents = rewrite(fs.readFileSync(path.join(source,name),'utf8'));
  if (name === 'studio.js') {
    contents = contents.replace(/function openAccount\(section\)\{[^\n]+/, "function openAccount(section){window.open(section==='billing'?'/account/wallet':section==='membership'?'/account/pricing':'/account','_top');}");
    contents = contents.replace(/if\(window\.ReizoDemoSession[^\n]*?return;\}/, '');
  }
  fs.writeFileSync(path.join(showcase,name),contents);
}
let preview = fs.readFileSync(path.join(source,'studio.html'),'utf8')
  .replace(/<script\b[^>]*src="([^"?]+)(?:\?[^"]*)?"[^>]*>[\s\S]*?<\/script>/g, (tag,name) => previewFiles.includes(name) ? tag : '')
  .replace(/<link\b[^>]*href="(account-welcome|account-avatar)\.css[^>]*>/g,'')
  .replace(/<dialog\b[^>]*id="site-login-dialog"[^>]*>[\s\S]*?<\/dialog>/g,'')
  .replace('<strong>我的账户</strong><small>未登录</small>', '<strong>工作台演示</strong><small>示例数据 · 不产生费用</small>');
preview = rewrite(preview).replace(/<a href="\/(?!reizo\/assets)/g,'<a target="_top" href="/');
fs.writeFileSync(path.join(showcase,'index.html'), preview);
